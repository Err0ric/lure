"""Arcanum taxonomy coverage: which codes the attack library tests, and
which it does not test yet.

Counts current attack versions only; pinned older versions are not mapped.
A code counts as tested by an attack's own payload, by a variant written in
its YAML (split, rephrased, translated), or by a generated variant (encoded,
and the invisible, homoglyph and hidden evasions). Buried variants add no
code.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

from lure import arcanum
from lure.attacks import Attack


@dataclass
class Coverage:
    attacks: list[str]
    # Code -> attack ids whose own payload carries it.
    base: dict[str, list[str]] = field(default_factory=dict)
    # Code -> "attack (variant)" for YAML variants that add it.
    variants: dict[str, list[str]] = field(default_factory=dict)
    # Code -> {variant id: number of attacks} for generated variants.
    generated: dict[str, dict[str, int]] = field(default_factory=dict)

    def tested(self, code: str) -> bool:
        return code in self.base or code in self.variants or code in self.generated


def build_coverage(attacks: Iterable[Attack]) -> Coverage:
    current = sorted((a for a in attacks if not a.pinned), key=lambda a: a.id)
    cov = Coverage([a.id for a in current])
    for attack in current:
        base = _codes(attack)
        for code in base:
            cov.base.setdefault(code, []).append(attack.id)
        for v in attack.variants:
            for code in _codes(attack.with_variant(v)) - base:
                cov.variants.setdefault(code, []).append(f"{attack.id} ({v.id})")
        yaml_ids = {v.id for v in attack.variants}
        for v in attack.all_variants():
            if v.source == "generated" and v.id not in yaml_ids:
                for code in _codes(attack.with_variant(v)) - base:
                    counts = cov.generated.setdefault(code, {})
                    counts[v.id] = counts.get(v.id, 0) + 1
    return cov


def _codes(attack: Attack) -> set[str]:
    return {c for codes in attack.arcanum.values() for c in codes}


def render_markdown(cov: Coverage) -> str:
    lines = [
        "# Arcanum taxonomy coverage",
        "",
        arcanum.ATTRIBUTION,
        "",
        (f"{arcanum.DISCLAIMER} Taxonomy v{arcanum.VERSION}, "
         f"[{arcanum.URL}]({arcanum.URL}), vendored from commit `{arcanum.COMMIT[:12]}` "
         "(see [THIRD_PARTY.md](../THIRD_PARTY.md))."),
        "",
        (f"Generated by `lure coverage` from the {len(cov.attacks)} current attacks. "
         "Pinned older versions are not mapped and not counted. A code is tested when an "
         "attack's own payload carries it, or a variant does (split, translated, encoded "
         "and the generated evasions); buried "
         "variants add no code. Nodes the taxonomy marks `LOCAL` need model weights and do "
         "not apply to the black-box targets Lure tests."),
        "",
        "| Pillar | Nodes | Tested | Not tested |",
        "| --- | --- | --- | --- |",
    ]
    by_pillar = _by_pillar()
    for pillar, codes in by_pillar.items():
        tested = sum(cov.tested(c) for c in codes)
        lines.append(f"| {pillar.title()} | {len(codes)} | {tested} | {len(codes) - tested} |")
    for pillar, codes in by_pillar.items():
        lines += ["", f"## {pillar.title()}s", "", "| Code | Name | Tested by |",
                  "| --- | --- | --- |"]
        for code in codes:
            lines.append(f"| {code} | {_cell(arcanum.title(code))} | {_tested_by(cov, code)} |")
    return "\n".join(lines) + "\n"


def _by_pillar() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {p: [] for p in arcanum.PILLARS}
    for code, node in arcanum.nodes().items():
        out[node["pillar"]].append(code)
    return {p: sorted(codes) for p, codes in out.items()}


def _tested_by(cov: Coverage, code: str) -> str:
    parts = list(cov.base.get(code, [])) + cov.variants.get(code, [])
    parts += [f"generated `{vid}` variant of {n} attack{'s' if n != 1 else ''}"
              for vid, n in sorted(cov.generated.get(code, {}).items())]
    if parts:
        return ", ".join(parts)
    if arcanum.nodes()[code].get("local"):
        return "not tested (`LOCAL`: needs model weights)"
    return "not tested"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def write_coverage(cov: Coverage, out: str | Path) -> Path:
    path = Path(out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown(cov), encoding="utf-8")
    return path
